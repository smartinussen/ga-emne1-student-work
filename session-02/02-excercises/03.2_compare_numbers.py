# Sammenlign to tall

first_number = int(input('Tast inn første heltall:'))
second_number = int(input('Tast inn andre heltall:'))

if first_number == second_number:
    print('Du har tastet inn like tall')
elif first_number > second_number:
    print('Første tall er større enn andre tall')
else:
    print('Andre tall er større enn første tall')

